#!/usr/bin/env bash
# gen-litellm-config.sh — generate services/litellm/config.yaml from the
# upstream LiteLLM catalog.
#
# The gateway (services/litellm.yml) mirrors every chat model the
# operator's LiteLLM proxy serves (GET /v1/models) and appends a local
# Ollama entry, wired as the DEFAULT FALLBACK for all models via
# litellm_settings.default_fallbacks — if an upstream model errors or
# times out, the router retries against the local small model.
#
# Env:
#   LITELLM_UPSTREAM_BASE_URL   default http://192.168.42.20:4000
#   LITELLM_UPSTREAM_API_KEY    upstream bearer key (or LITELLM_API_KEY)
#   OLLAMA_MODEL                fallback model, default llama3.2:1b
#
# Embedding models (nomic-embed-text, text-embedding-*) are skipped —
# this gateway fronts CHAT surfaces (OpenWebUI, portal helpers).
#
# Idempotent: re-running refreshes the catalog in place.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${REPO_ROOT}/services/litellm/config.yaml"
BASE="${LITELLM_UPSTREAM_BASE_URL:-}"
KEY="${LITELLM_UPSTREAM_API_KEY:-${LITELLM_API_KEY:-}}"
FALLBACK_MODEL="${OLLAMA_MODEL:-llama3.2:1b}"

[[ -n "$BASE" ]] || { echo "gen-litellm-config: need LITELLM_UPSTREAM_BASE_URL (operator LiteLLM proxy, see .env)" >&2; exit 1; }
[[ -n "$KEY" ]] || { echo "gen-litellm-config: need LITELLM_UPSTREAM_API_KEY or LITELLM_API_KEY" >&2; exit 1; }

python3 - "$BASE" "$KEY" "$FALLBACK_MODEL" > "${OUT}.tmp" <<'PY'
import json, sys, urllib.request

base, key, fallback = sys.argv[1], sys.argv[2], sys.argv[3]
req = urllib.request.Request(base.rstrip('/') + '/models',
                             headers={'Authorization': 'Bearer ' + key})
data = json.load(urllib.request.urlopen(req, timeout=15))
ids = sorted({m.get('id') for m in data.get('data', []) if m.get('id')})

def is_chat(mid: str) -> bool:
    low = mid.lower()
    return 'embed' not in low and not low.startswith('text-embedding')

chat = [m for m in ids if is_chat(m)]

print('# GENERATED by scripts/gen-litellm-config.sh — do not edit by hand.')
print('# Model list mirrors the upstream LiteLLM catalog (%d chat models);' % len(chat))
print('# llama3.2-style local Ollama entry is the default fallback.')
print()
print('model_list:')
print('  # local fallback (monitoring/ollama.yml)')
print(f'  - model_name: {fallback}')
print('    litellm_params:')
print(f'      model: ollama/{fallback}')
print('      api_base: http://ollama:11434')
for mid in chat:
    print(f'  - model_name: {mid}')
    print('    litellm_params:')
    print(f'      model: openai/{mid}')
    print('      api_base: os.environ/LITELLM_UPSTREAM_BASE_URL')
    print('      api_key: os.environ/LITELLM_UPSTREAM_API_KEY')
print()
print('litellm_settings:')
print(f'  default_fallbacks: [{fallback}]')
print()
print('general_settings:')
print('  master_key: os.environ/LITELLM_MASTER_KEY')
PY

mv "${OUT}.tmp" "$OUT"
echo "gen-litellm-config: wrote $OUT ($(grep -c 'model_name:' "$OUT") model entries)"
