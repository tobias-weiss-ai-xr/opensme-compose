#!/usr/bin/env python3
"""
aggregate_sbom.py — build a fleet-level CycloneDX SBOM from per-image SBOMs.

Input: docs/sbom/*.cdx.json generated by syft, plus the canonical inventory.
Output: fleet.cdx.json with one container component per unique image digest.

Exit 1 if an inventory image in the selected set has no SBOM.
"""

import argparse
import json
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def inventory_rows(path: Path) -> list[dict]:
    rows = []
    with path.open() as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 4 or parts[0] == "service":
                continue
            rows.append({"service": parts[0], "image": parts[1],
                         "digest": parts[2], "source": parts[3]})
    return rows


def find_bom(cdx_dir: Path, image: str) -> Path | None:
    # Filenames are service-safe-hash; scan metadata rather than guessing.
    for path in sorted(cdx_dir.glob("*.cdx.json")):
        if path.name == "fleet.cdx.json":
            continue
        try:
            doc = json.loads(path.read_text())
        except Exception:
            continue
        comp = (doc.get("metadata") or {}).get("component") or {}
        if comp.get("name") == image:
            return path
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description="aggregate fleet CycloneDX SBOM")
    parser.add_argument("--dir", required=True, help="SBOM directory")
    parser.add_argument("--inventory", required=True, help="inventory TSV")
    parser.add_argument("--images", nargs="*", default=None,
                        help="image refs to include (default: all inventory)")
    parser.add_argument("--out", required=True, help="output fleet.cdx.json")
    parser.add_argument("--allow-missing", action="store_true",
                        help="include inventory images without per-image SBOM as placeholders")
    args = parser.parse_args()

    cdx_dir = Path(args.dir)
    rows = inventory_rows(Path(args.inventory))
    # Accept both space- and comma-separated image references.
    wanted = []
    for token in (args.images or []):
        wanted.extend(part for part in token.split(",") if part)
    if not wanted:
        wanted = [r["image"] for r in rows]

    by_image = {r["image"]: r for r in rows}
    components = []
    seen = set()
    missing = []

    for image in wanted:
        bom = find_bom(cdx_dir, image)
        if bom is None:
            if args.allow_missing:
                digest = by_image.get(image, {}).get("digest", "-")
                key = digest if digest and digest != "-" else image
                if key not in seen:
                    seen.add(key)
                    components.append({
                        "type": "container",
                        "name": image,
                        "bom-ref": key,
                        "properties": [
                            {"name": "openSME:image", "value": image},
                            {"name": "openSME:digest", "value": digest},
                            {"name": "openSME:sbom", "value": "missing"},
                        ],
                    })
            else:
                missing.append(image)
            continue
        doc = json.loads(bom.read_text())
        comp = (doc.get("metadata") or {}).get("component") or {}
        digest = by_image.get(image, {}).get("digest", "-")
        # Prefer the digest from the image reference / inventory; fall back to
        # the Syft bom-ref so duplicates are still stable.
        key = digest if digest and digest != "-" else comp.get("bom-ref") or image
        if key in seen:
            continue
        seen.add(key)
        components.append({
            "type": "container",
            "name": image,
            "bom-ref": key,
            "properties": [
                {"name": "openSME:image", "value": image},
                {"name": "openSME:digest", "value": digest},
            ],
        })

    if missing:
        print("aggregate_sbom: missing per-image SBOMs:", file=sys.stderr)
        for image in missing:
            print(f"  ✗ {image}", file=sys.stderr)
        return 1

    aggregate = {
        "$schema": "http://cyclonedx.org/schema/bom-1.7.schema.json",
        "bomFormat": "CycloneDX",
        "specVersion": "1.7",
        "serialNumber": f"urn:uuid:{uuid.uuid4()}",
        "version": 1,
        "metadata": {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "tools": [{"type": "application", "name": "openSME-sbom-aggregate"}],
            "component": {
                "type": "application",
                "name": "openSME fleet",
                "bom-ref": "openSME-fleet",
            },
        },
        "components": sorted(components, key=lambda c: c["name"]),
    }
    Path(args.out).write_text(json.dumps(aggregate, indent=2) + "\n")
    print(f"aggregate_sbom: {len(components)} unique image component(s) -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
