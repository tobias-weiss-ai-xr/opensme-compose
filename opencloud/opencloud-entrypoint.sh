#!/bin/sh
# OpenCloud entrypoint — generate config on first run.
set -e

# ── Validate required environment variables ──────────────────────────────
echo "opencloud-entrypoint: validating environment..." >&2
for var in OC_ADMIN_USERNAME OC_ADMIN_PASSWORD OC_DOMAIN; do
  eval val=\$$"\$var"
  if [ -z "$val" ]; then
    echo "opencloud-entrypoint: ERROR: required environment variable $var is not set" >&2
    exit 1
  fi
done
echo "opencloud-entrypoint: environment validated." >&2

# ── Generate initial config if it does not exist ────────────────────────
if [ ! -f /etc/opencloud/opencloud.yaml ]; then
  echo "opencloud-entrypoint: no config found, running init..." >&2
  # Handle self-signed cert scenarios via OC_INSECURE
  INIT_INSECURE=""
  if [ "${OC_INSECURE:-}" = "true" ] || [ "${OC_INSECURE:-}" = "1" ]; then
    INIT_INSECURE="--insecure=true"
  fi
  opencloud init -f $INIT_INSECURE
  echo "opencloud-entrypoint: config generated." >&2
fi

# ── Configure CORS for cross-app access ────────────────────────────────
# Read PROXY_CORS_ALLOW_ORIGIN (comma-separated) with sensible defaults for
# the OpenSME fleet apps: home, notes, paperless, invoices.
PROXY_CORS_ORIGINS="${PROXY_CORS_ALLOW_ORIGIN:-https://home.opensme.graphwiz.ai,https://notes.opensme.graphwiz.ai,https://paperless.opensme.graphwiz.ai,https://invoices.opensme.graphwiz.ai}"

echo "opencloud-entrypoint: configuring CORS allow origins: $PROXY_CORS_ORIGINS" >&2

# Generate proxy.yaml with CORS section
cat > /etc/opencloud/proxy.yaml <<PROXY_EOF
# OpenCloud proxy configuration — generated by opencloud-entrypoint.sh
# CORS settings for cross-app access in the OpenSME fleet.
proxy:
  cors:
    allowed_origins:
PROXY_EOF

# Convert comma-separated origins to YAML list format
for origin in $(echo "$PROXY_CORS_ORIGINS" | tr ',' '\n'); do
  # Trim whitespace
  origin=$(echo "$origin" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
  if [ -n "$origin" ]; then
    echo "    - '$origin'" >> /etc/opencloud/proxy.yaml
  fi
done

echo "opencloud-entrypoint: proxy.yaml with CORS configuration generated." >&2

# ── Configure default spaces ────────────────────────────────────────────
# Ensure /Shared/Portal, /Shared/Polls, /Shared/Intercom exist for app integrations.
DEFAULT_SPACES="/Shared/Portal /Shared/Polls /Shared/Intercom"

echo "opencloud-entrypoint: ensuring default spaces exist..." >&2

# Build OC_INSECURE flag for opencloud CLI
OC_CLI_INSECURE=""
if [ "${OC_INSECURE:-}" = "true" ] || [ "${OC_INSECURE:-}" = "1" ]; then
  OC_CLI_INSECURE="--insecure"
fi

for space in $DEFAULT_SPACES; do
  # Check if the space already exists using the opencloud CLI
  if ! opencloud $OC_CLI_INSECURE space list --path "$space" >/dev/null 2>&1; then
    echo "opencloud-entrypoint: creating space: $space" >&2
    # The opencloud CLI 'space create' expects a path like /Shared/Portal
    # We use the admin credentials from the environment
    opencloud $OC_CLI_INSECURE space create \
      --path "$space" \
      --admin_username "$OC_ADMIN_USERNAME" \
      --admin_password "$OC_ADMIN_PASSWORD" \
      --domain "$OC_DOMAIN" || echo "opencloud-entrypoint: WARNING: failed to create space $space" >&2
  else
    echo "opencloud-entrypoint: space already exists: $space" >&2
  fi
done

echo "opencloud-entrypoint: default spaces ensured." >&2

# ── Render the CSP file from the template ───────────────────────────────
# The upstream default CSP refuses to frame the IdP (needed for oidc silent-
# token renewal), so we inject the IdP origin into child-src/connect-
# src/frame-src. The issuer (OC_OIDC_ISSUER) is the bare origin; strip any
# trailing path.
IDP_ORIGIN="${OC_OIDC_ISSUER:-}"
case "$IDP_ORIGIN" in
  *://*)
    IDP_ORIGIN="${IDP_ORIGIN%%/*}"   # drop path (keeps scheme://host[:port])
    ;;
esac
if [ -f /etc/opencloud/csp.tpl.yaml ] && [ -n "$IDP_ORIGIN" ]; then
  sed "s|__IDP_ORIGIN__|$IDP_ORIGIN|g" \
      /etc/opencloud/csp.tpl.yaml > /etc/opencloud/csp.yaml
  echo "opencloud-entrypoint: csp.yaml rendered (idp=$IDP_ORIGIN)" >&2
elif [ -f /etc/opencloud/csp.tpl.yaml ]; then
  # No issuer configured — fall back to the upstream default (no IdP origin).
  sed "/__IDP_ORIGIN__/d" /etc/opencloud/csp.tpl.yaml > /etc/opencloud/csp.yaml
  echo "opencloud-entrypoint: csp.yaml rendered without idp origin" >&2
fi

# ── Start the server ────────────────────────────────────────────────────
exec opencloud server
