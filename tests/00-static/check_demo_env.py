#!/usr/bin/env python3
"""
tests/00-static/check_demo_env.py — Demo .env completeness.

`scripts/demo.sh` generates a fresh .env and is the entry point for every E2E
CI job. Compose interpolates ALL services in a project before filtering by
profile, so a single `${VAR:?}` guard that the generator does not fill aborts
`docker compose up` before any container starts — the job then fails with no
useful log.

This check compares the fail-closed guards in the demo compose chain against
the variables scripts/demo.sh writes, without needing Docker.

Usage:
    python3 tests/00-static/check_demo_env.py

Exit codes:
    0 = generator covers every required variable
    1 = at least one required variable is missing
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from conftest import Result, ROOT

# The compose chain booted by scripts/demo.sh (and by the E2E jobs).
DEMO_CHAIN = [
    "docker-compose.yml",
    "idm/zitadel.yml",
    "opencloud/opencloud.yml",
    "profiles/demo.dev.yml",
]

REQUIRED_RE = re.compile(r"\$\{([A-Z][A-Z0-9_]*):\?")
ASSIGN_RE = re.compile(r"^([A-Z][A-Z0-9_]*)=")
PRINTF_RE = re.compile(r"printf\s+'([^']*)'")


def required_vars() -> set[str]:
    """Variables compose refuses to start without (fail-closed guards)."""
    found: set[str] = set()
    for rel in DEMO_CHAIN:
        path = ROOT / rel
        if not path.exists():
            continue
        found |= set(REQUIRED_RE.findall(path.read_text()))
    return found


def generated_vars() -> set[str]:
    """Variables scripts/demo.sh writes into .env.

    Covers the initial heredoc and the upgrade-append block (printf literals),
    so both a fresh install and an older .env stay bootable.
    """
    path = ROOT / "scripts/demo.sh"
    text = path.read_text()
    found: set[str] = set()

    # Initial generation: KEY=value lines inside the ENVEOF heredoc.
    for line in text.splitlines():
        m = ASSIGN_RE.match(line)
        if m:
            found.add(m.group(1))

    # Upgrade appends: printf '...KEY=%s...' patterns.
    for literal in PRINTF_RE.findall(text):
        found |= set(re.findall(r"([A-Z][A-Z0-9_]*)=", literal))

    return found


def main() -> int:
    result = Result("demo-env")
    result.header("Layer 0: Demo .env completeness")

    req = required_vars()
    gen = generated_vars()
    result.info(f"{len(req)} required vars in the demo chain, {len(gen)} written by demo.sh")

    missing = sorted(req - gen)
    if missing:
        for var in missing:
            result.fail(f"{var} is required by the demo chain but scripts/demo.sh never sets it")
        result.info("A fresh `docker compose up` would abort before starting any container")
    else:
        result.ok("every required variable is generated by scripts/demo.sh")

    return result.summary()


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
