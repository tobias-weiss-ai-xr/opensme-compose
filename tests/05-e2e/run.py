def probe(session, url) -> bool:
    try:
        session.get(url, timeout=5, allow_redirects=True)
        return True
    except requests.RequestException:
        return False


def section_discovery(result, session, idp_base):
    try:
        r = session.get(f"{idp_base}/.well-known/openid-configuration", timeout=T)
    except requests.RequestException as e:
        result.fail(f"IdP discovery unreachable: {e.__class__.__name__}")
        return None
    if r.status_code != 200:
        result.fail(f"openid-configuration: HTTP {r.status_code}")
        return None
    disc = r.json()
    missing = [
        k for k in ("issuer", "authorization_endpoint", "token_endpoint", "jwks_uri")
        if not disc.get(k)
    ]
    if missing:
        result.fail(f"discovery missing keys: {missing}")
        return None
    result.ok(f"OIDC discovery ok (issuer {disc['issuer']})")

    issuer_host = urlparse(disc["issuer"]).netloc
    if issuer_host and issuer_host != urlparse(idp_base).netloc:
        result.warn(f"issuer host {issuer_host} != configured host")
    try:
        jwks = session.get(disc["jwks_uri"], timeout=T)
        keys = len(jwks.json().get("keys", [])) if jwks.status_code == 200 else 0
        (result.ok if keys else result.fail)(f"JWKS: {keys} key(s)")
    except requests.RequestException:
        result.fail("JWKS unreachable")
    return disc


def section_portal(result, session, portal_base, ai_configured=False):
    try:
        r = session.get(portal_base + "/", timeout=T)
    except requests.RequestException:
        result.skip("portal unreachable")
        return
    if r.status_code != 200:
        result.fail(f"portal /: HTTP {r.status_code}")
    elif "openSME" not in r.text and "opensme" not in r.text.lower():
        result.fail("portal / does not mention openSME")
    else:
        result.ok("portal landing page ok")

    # Trust & transport: plain HTTP must bounce to HTTPS (when served via
    # Traefik; the plain-localhost variant is skipped). Retried: during the
    # first seconds of a fresh traefik boot internal routers may be rebuilt
    # after the web entrypoint answers — a transient 404 must not fail the
    # suite.
    if portal_base.startswith("https://"):
        rr, loc = None, ""
        for attempt in range(4):
            try:
                rr = session.get("http://" + portal_base[len("https://"):],
                                 allow_redirects=False, timeout=T)
                loc = rr.headers.get("Location", "")
                if rr.status_code in REDIRECTS and loc.startswith("https://"):
                    break
            except requests.RequestException as e:
                result.warn(f"HTTP→HTTPS probe failed: "
                            f"{e.__class__.__name__}")
            time.sleep(2)
        if rr is None:
            pass  # probe never got through — already warned above
        elif rr.status_code in REDIRECTS and loc.startswith("https://"):
            result.ok("plain HTTP redirects to HTTPS")
        else:
            result.fail(f"HTTP did not redirect to HTTPS: "
                        f"{rr.status_code} {loc[:60]}")

    # Trust in depth: security headers must survive 404s (they guard every
    # response, not just the happy path)
    try:
        miss404 = [
            f"{k}={v}" for k, v in {
                "x-content-type-options": "nosniff",
                "x-frame-options": "DENY",
            }.items() if v not in (session.get(portal_base + "/e2e-not-a-page",
                                               timeout=T).headers.get(k) or "")
        ]
        (result.ok if not miss404 else result.fail)(
            "security headers present on 404 responses" if not miss404
            else f"404 responses lack headers: {'; '.join(miss404)}"
        )
    except requests.RequestException as e:
        result.fail(f"404 header probe failed: {e.__class__.__name__}")

    # security-header contract (must match the middleware in portal/src/main.rs)
    want = {
        "x-content-type-options": "nosniff",
        "x-frame-options": "DENY",
        "referrer-policy": "strict-origin-when-cross-origin",
        "content-security-policy": "default-src 'self'",
    }
    missing = [
        f"{k}={v!r}"
        for k, v in want.items()
        if v not in (r.headers.get(k) or "")
    ]
    (result.ok if not missing else result.fail)(
        "portal security headers ok" if not missing
        else f"portal security headers missing/changed: {'; '.join(missing)}"
    )

    try:
        h = session.get(portal_base + "/health", timeout=T)
        ok = h.status_code == 200 and h.json().get("status") == "ok"
        (result.ok if ok else result.fail)(
            "portal /health ok" if ok else f"portal /health: HTTP {h.status_code} {h.text[:60]}"
        )
        s = session.get(portal_base + "/api/services", timeout=T)
        services = s.json().get("services") if s.status_code == 200 else None
        (result.ok if isinstance(services, list) else result.fail)(
            f"portal /api/services: {len(services)} service(s)" if isinstance(services, list)
            else f"portal /api/services: HTTP {s.status_code}"
        )

        # Truthful catalog: every advertised service must actually answer.
        # The portal must not promise what isn't there.
        if isinstance(services, list):
            dead = []
            for svc in services:
                href = str(svc.get("url") or svc.get("href") or "")
                if not href:
                    dead.append(f"{svc.get('name')!r}: no url")
                    continue
                try:
                    rs = session.get(href, timeout=T, allow_redirects=True)
                    if rs.status_code >= 500:
                        dead.append(f"{svc.get('name')!r}: HTTP {rs.status_code}")
                except requests.RequestException:
                    dead.append(f"{svc.get('name')!r}: unreachable")
            (result.ok if not dead else result.fail)(
                f"all {len(services)} advertised service(s) reachable"
                if not dead else f"catalog lies about: {'; '.join(dead)}"
            )

        # announcements consumer contract: array of {level in info|warn,
        # non-empty text}, capped — this is what app.js renders into HTML
        a = session.get(portal_base + "/api/announcements", timeout=T)
        ann = a.json().get("announcements") if a.status_code == 200 else None
        if not isinstance(ann, list):
            result.fail(f"portal /api/announcements: HTTP {a.status_code}")
        else:
            bad = [
                f"item {i}: level={x.get('level')!r} text={bool(x.get('text', '').strip())}"
                for i, x in enumerate(ann)
                if not isinstance(x, dict)
                or x.get("level") not in ("info", "warn")
                or not str(x.get("text", "")).strip()
            ]
            capped = len(ann) <= 8
            (result.ok if not bad and capped else result.fail)(
                f"portal /api/announcements schema ok ({len(ann)} item(s))"
                if not bad and capped
                else f"portal /api/announcements bad: {'; '.join(bad) or 'cap exceeded'}"
            )

        # AI card gating: the endpoint (and its UI card) must stay hidden
        # unless the operator configured AI_API_URL
        has_card = "id=\"ai-card\"" in r.text
        if has_card == ai_configured:
            result.ok("AI card visibility matches configuration"
                      if has_card else "AI card hidden (AI unconfigured)")
        else:
            result.fail(
                "AI card visible but AI_API_URL unset (must stay hidden)"
                if has_card else "AI_API_URL set but no ai-card rendered"
            )
    except (requests.RequestException, ValueError) as e:
        result.fail(f"portal API: {e.__class__.__name__}")


def run_auth_code_flow(result, session, disc, client_id, csec, idp_base,
                       lc_pat, client_uid, login_name, login_uid, pw, callback):
    """Step 3: full authorization-code + PKCE round trip. Returns id_token + session."""
    authz, verifier, state, nonce = authorize_url(disc, client_id, callback)
    qs, sess = api_login(session, idp_base, lc_pat, client_uid, authz, login_uid, pw)
    if qs.get("state", [None])[0] != state:
        raise E2EError("state mismatch at callback")
    result.ok("login flow produced an authorization code")

    tok = session.post(
        disc["token_endpoint"],
        data={
            "grant_type": "authorization_code",
            "code": qs["code"][0],
            "redirect_uri": callback,
            "client_id": client_id,
            "code_verifier": verifier,
        },
        auth=(client_id, csec) if csec else None,
        timeout=T,
    )
    if tok.status_code != 200:
        raise E2EError(f"token endpoint: HTTP {tok.status_code} {tok.text[:120]}")
    body = tok.json()
    access = body.get("access_token")
    idt = body.get("id_token")
    if not access or not idt:
        raise E2EError("token response missing access/id tokens")
    if len(idt.split(".")) != 3:
        raise E2EError("id_token is not a JWS compact token")
    result.ok("PKCE token exchange ok")

    ui = session.get(
        disc.get("userinfo_endpoint", f"{idp_base}/oidc/v1/userinfo"),
        headers={"Authorization": f"Bearer {access}"},
        timeout=T,
    )
    if ui.status_code != 200:
        raise E2EError(f"userinfo: HTTP {ui.status_code}")
    preferred = ui.json().get("preferred_username", "")
    stem = login_name.split("@")[0]
    if stem.lower() not in str(preferred).lower():
        raise E2EError(f"userinfo subject {preferred!r} does not match {stem!r}")
    result.ok(f"userinfo authenticated as {preferred}")
    return idt, sess, nonce


