def b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def make_pkce():
    verifier = b64url(secrets.token_bytes(48))
    challenge = b64url(hashlib.sha256(verifier.encode()).digest())
    return verifier, challenge


def authorize_url(disc, client_id, callback, scope="openid profile email"):
    verifier, challenge = make_pkce()
    state, nonce = secrets.token_urlsafe(16), secrets.token_urlsafe(16)
    qs = urlencode(
        {
            "client_id": client_id,
            "redirect_uri": callback,
            "response_type": "code",
            "scope": scope,
            "state": state,
            "nonce": nonce,
            "code_challenge": challenge,
            "code_challenge_method": "S256",
        }
    )
    return f"{disc['authorization_endpoint']}?{qs}", verifier, state, nonce


# ─────────────────────────────────────────────────────────────────────────────
# Seeded machine credentials (docker compose cp from the running zitadel)
# ─────────────────────────────────────────────────────────────────────────────

def fetch_seeded(container_path):
    """Read a seeded credential file from the running zitadel container.

    Tries the overlay set from $COMPOSE_FILE first, then the standard
    demo quartet (scripts/demo.sh), then base + idm — whatever defines a
    `zitadel` service wins. Returns the file content or None.
    """
    sets = []
    if os.environ.get("COMPOSE_FILE"):
        sets.append(os.environ["COMPOSE_FILE"].split(os.pathsep))
    sets.append([
        "docker-compose.yml",
        "idm/zitadel.yml",
        "opencloud/opencloud.yml",
        "profiles/demo.dev.yml",
    ])
    sets.append(["docker-compose.yml", "idm/zitadel.yml"])
    for files in sets:
        cmd = ["docker", "compose"]
        cmd += [arg for f in files for arg in ("-f", f)]
        if (ROOT / ".env").exists():
            cmd += ["--env-file", ".env"]
        cmd += ["cp", f"zitadel:{container_path}", "-"]
        try:
            # docker may be absent, the set not deployed, or the read times
            # out — every failure just means "try the next candidate set".
            r = subprocess.run(
                cmd, cwd=str(ROOT), capture_output=True, timeout=30, check=False,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if r.returncode != 0:
            continue
        try:
            with tarfile.open(fileobj=io.BytesIO(r.stdout)) as tf:
                for member in tf.getmembers():
                    if member.isfile():
                        return tf.extractfile(member).read().decode().strip()
        except tarfile.TarError:
            continue
    return None


# ─────────────────────────────────────────────────────────────────────────────
# Zitadel Management API (machine PAT) — throw-away OIDC app bootstrap
# ─────────────────────────────────────────────────────────────────────────────

def mgmt(session, idp_base, pat, method, path, payload=None):
    return session.request(
        method,
        idp_base + path,
        json=payload if payload is not None else None,
        headers={"Authorization": f"Bearer {pat}"},
        timeout=T,
    )


def bootstrap_app(session, idp_base, pat, callback, post_logout):
    """Create (or reuse) a throw-away PKCE OIDC app. Returns (client_id, pid, app_id)."""
    proj_name = "e2e-sso"
    r = mgmt(session, idp_base, pat, "POST", "/management/v1/projects/_search", {})
    if r.status_code != 200:
        raise E2EError(f"project search failed: HTTP {r.status_code}")
    pid = next(
        (p["id"] for p in r.json().get("result", []) if p.get("name") == proj_name), None
    )
    if pid is None:
        r = mgmt(session, idp_base, pat, "POST", "/management/v1/projects",
                 {"name": proj_name})
        if r.status_code != 200:
            raise E2EError(f"project add failed: HTTP {r.status_code} {r.text[:120]}")
        pid = r.json().get("id")
    else:
        # Leftover from a crashed earlier run: remove stale apps so app-add
        # can't 409 (an old app's client id would also mismatch our PKCE
        # callback, and its secret is unrecoverable).
        r = mgmt(session, idp_base, pat, "POST",
                 f"/management/v1/projects/{pid}/apps/_search", {})
        if r.status_code == 200:
            for app in r.json().get("result", []):
                if app.get("name") == "e2e-sso":
                    mgmt(session, idp_base, pat, "DELETE",
                         f"/management/v1/projects/{pid}/apps/{app['id']}")
    body = {
        "name": "e2e-sso",
        "redirectUris": [callback],
        "postLogoutRedirectUris": [post_logout],
        "responseTypes": ["OIDC_RESPONSE_TYPE_CODE"],
        "grantTypes": ["OIDC_GRANT_TYPE_AUTHORIZATION_CODE"],
        "appType": "OIDC_APP_TYPE_WEB",
        "authMethodType": "OIDC_AUTH_METHOD_TYPE_NONE",  # public client, PKCE only
        "devMode": True,  # relax redirect-uri scheme checks (local domains)
    }
    r = mgmt(session, idp_base, pat, "POST",
             f"/management/v1/projects/{pid}/apps/oidc", body)
    if r.status_code != 200:
        raise E2EError(f"oidc app add failed: HTTP {r.status_code} {r.text[:120]}")
    data = r.json()
    return data.get("clientId"), pid, data.get("appId")


def cleanup_app(session, idp_base, pat, pid, app_id):
    if app_id:
        mgmt(session, idp_base, pat, "DELETE",
             f"/management/v1/projects/{pid}/apps/{app_id}")
    if pid:
        mgmt(session, idp_base, pat, "DELETE", f"/management/v1/projects/{pid}")


# ─────────────────────────────────────────────────────────────────────────────
# Zitadel v2 Session API — programmatic login (what the Login v2 UI does)
# ─────────────────────────────────────────────────────────────────────────────

def lc_headers(lc_pat, user_id):
    return {
        "Authorization": f"Bearer {lc_pat}",
        "x-zitadel-login-client": user_id,
    }


def resolve_user_id(session, idp_base, auth_value, login_name):
    """Find the userId for a login name (Management API user search; the
    v2 _by_login_name endpoint 404s until the login_names projection is
    fully warm). Matches machine users (bare name) and human users
    (org-domain suffixed name)."""
    r = session.post(
        f"{idp_base}/management/v1/users/_search",
        json={"userName": login_name.split("@")[0]},
        headers={"Authorization": f"Bearer {auth_value}"},
        timeout=T,
    )
    if r.status_code != 200:
        return None
    stem = login_name.split("@")[0].lower()
    for u in r.json().get("result", []):
        if str(u.get("userName", "")).lower().split("@")[0] == stem:
            return str(u.get("id"))
    return None


def api_login(session, idp_base, lc_pat, client_uid, authz_url, user_id, pw):
    """Log a user in via the v2 Session API and finalize the OIDC auth request.

    Returns (callback_query: dict, session: {id, token}).
    Raises E2EError on any non-2xx step.
    """
    h = lc_headers(lc_pat, client_uid)

    # (a) probe the authorize endpoint — expect a redirect to the login UI
    #     carrying the auth request id (do NOT follow it)
    r = session.get(authz_url, headers=h, allow_redirects=False, timeout=T)
    if r.status_code not in REDIRECTS or "Location" not in r.headers:
        raise E2EError(f"authorize probe: HTTP {r.status_code} {r.text[:80]}")
    m = re.search(r"authRequest=([A-Za-z0-9_:-]+)", r.headers["Location"])
    if not m:
        raise E2EError("authorize did not hand out an auth request id")
    req_id = m.group(1)

    # (b) create a session with the user check
    r = session.post(
        f"{idp_base}/v2/sessions",
        json={"checks": {"user": {"userId": user_id}}},
        headers=h, timeout=T,
    )
    if r.status_code >= 300:
        raise E2EError(f"session create: HTTP {r.status_code} {r.text[:80]}")
    j = r.json()
    sid, stok = j.get("sessionId"), j.get("sessionToken")
    if not sid or not stok:
        raise E2EError("session create returned no id/token")

    # (c) password check (returns the current session token)
    r = session.patch(
        f"{idp_base}/v2/sessions/{sid}",
        json={"checks": {"password": {"password": pw}}},
        headers=h, timeout=T,
    )
    if r.status_code >= 300:
        raise E2EError(
            f"password check: HTTP {r.status_code} "
            f"(wrong E2E_ZITADEL_LOGIN_NAME / ZITADEL_ADMIN_PASSWORD?)"
        )
    stok = r.json().get("sessionToken") or stok

    # (d) finalize the auth request with the session → callback URL
    qs = finalize(session, idp_base, lc_pat, client_uid, req_id, sid, stok)
    return qs, {"id": sid, "token": stok, "req": req_id}


def finalize(session, idp_base, lc_pat, client_uid, req_id, sid, stok):
    """Attach a session to an auth request; returns the callback query params."""
    r = session.post(
        f"{idp_base}/v2/oidc/auth_requests/{req_id}",
        json={"session": {"sessionId": sid, "sessionToken": stok}},
        headers=lc_headers(lc_pat, client_uid), timeout=T,
    )
    if r.status_code >= 300:
        raise E2EError(f"finalize auth request: HTTP {r.status_code} {r.text[:80]}")
    cb = r.json().get("callbackUrl", "")
    qs = parse_qs(urlparse(cb).query)
    if "code" not in qs:
        raise E2EError(f"callback without code: {sorted(qs)}")
    return qs


def terminate(session, idp_base, lc_pat, client_uid, sid, stok):
    """Terminate an IdP session (DELETE /v2/sessions/{id}, token in body)."""
    r = session.delete(
        f"{idp_base}/v2/sessions/{sid}",
        json={"sessionToken": stok},
        headers=lc_headers(lc_pat, client_uid), timeout=T,
    )
    return r.status_code < 300


# ─────────────────────────────────────────────────────────────────────────────
# Portal login (intercom/polls are authenticated surfaces)
# ─────────────────────────────────────────────────────────────────────────────

def portal_login(session, portal_base, idp_base, disc=None, client_id=None):
    """Drive the portal's real OIDC login so `session` carries OPENSMESESSION.

    The intercom/polls endpoints only answer signed-in users (the Rust
    middleware rejects everything else with 401 — the wall this program
    proves). The portal mints an OAuth `state` and binds it in an HttpOnly
    cookie; the whole round trip must go through the real /api/auth/login →
    IdP (v2 sessions + password + finalize) → /api/auth/callback chain,
    which lands the OPENSMESESSION cookie back in the requests session.

    Falls back to the demo stack's .env configuration for the IdP
    credentials unless overrides are passed via env. Returns True on
    success. On failure the session is left unauthenticated so callers can
    report it instead of silently proceeding.
    """
    dotenv = load_env_file()

    def cfg(key, default=""):
        return os.environ.get(key) or dotenv.get(key) or default

    if client_id is None:
        client_id = cfg("PORTAL_OIDC_CLIENT_ID", "opensme-portal")
    login_name = cfg("E2E_ZITADEL_LOGIN_NAME", "zitadel-admin")
    pw = cfg("ZITADEL_ADMIN_PASSWORD")
    # The E2E_* overrides are optional: on a booted stack the seeded
    # login-client PAT rides the v2 Session API (same source the
    # logout/lifecycle journeys use). Without this fallback portal_login
    # bails out on stock demo/Ci stacks where .env has no E2E_* overrides.
    lc_pat = cfg("E2E_ZITADEL_LOGINCLIENT_PAT") or fetch_seeded("/machinekey/login-client.pat")
    if not (pw and lc_pat):
        return False
    pat = cfg("E2E_ZITADEL_PAT") or fetch_seeded("/machinekey/pat")
    if not pat:
        return False
    if disc is None:
        try:
            disc = session.get(
                f"{idp_base}/.well-known/openid-configuration", timeout=T
            ).json()
        except requests.RequestException:
            return False
    # Prefer the machine PAT (admin) for the Management-API user lookup —
    # the login-client PAT may be too narrow-privileged to resolve users.
    client_uid = resolve_user_id(session, idp_base, pat or lc_pat, login_name)
    if not client_uid:
        return False

    # 1) start the flow — capture the authorize Location + state cookie
    stage = "start"
    try:
        r = session.get(
            portal_base + "/api/auth/login", allow_redirects=False, timeout=T
        )
        if r.status_code not in REDIRECTS or "Location" not in r.headers:
            stage = f"authorize: HTTP {r.status_code}, no Location"
            return False
        authz_url = r.headers["Location"]
        if client_id and client_id not in authz_url:
            stage = (f"authorize client mismatch: want {client_id!r} in "
                     f"{authz_url[:90]!r}")
            return False
        # capture the state cookie + raw Set-Cookie exactly as the portal
        # delivered them right after the login 303
        post_login = session.cookies.get("OPENSMESTATE")
        raw_sc = r.headers.get("set-cookie", "")[:120]
        # 2) IdP leg: v2 session + password check + finalize
        qs, _session = api_login(
            session, idp_base, lc_pat, client_uid, authz_url, client_uid, pw
        )
        echoed = (qs.get("state") or [None])[0]
        pre_cb = session.cookies.get("OPENSMESTATE")
        # 3) callback with the portal's own state → OPENSMESESSION cookie
        cb = f"{portal_base}/api/auth/callback?{urlencode(qs)}"
        r = session.get(cb, allow_redirects=False, timeout=T)
        if r.status_code not in REDIRECTS or not session.cookies.get("OPENSMESESSION"):
            stage = (
                f"callback: HTTP {r.status_code}, "
                f"cookie={'yes' if session.cookies.get('OPENSMESESSION') else 'no'}, "
                f"qs={sorted(qs) if qs else []}, "
                f"state_cookie={'yes' if session.cookies.get('OPENSMESTATE') else 'no'}, "
                f"post_login={'yes' if post_login else 'no'}, "
                f"pre_cb={'yes' if pre_cb else 'no'}, "
                f"post_login_val={(post_login or '')[:6]!r}, "
                f"echo_val={(echoed or '')[:6]!r}, "
                f"sc_raw={raw_sc!r}"
            )
            return False
        return True
    except (E2EError, KeyError, requests.RequestException) as exc:
        stage = f"exception {type(exc).__name__}: {exc}"
        return False
    finally:
        if os.environ.get("E2E_DEBUG") and not session.cookies.get("OPENSMESESSION"):
            print(f"  [diag]   portal_login failed: {stage}", flush=True)


