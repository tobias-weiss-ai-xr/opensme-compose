def section_opencloud(result: Result, session, cloud_base: str, idp_base: str,
                      client_id: str = "opencloud"):
    """Files & collaboration: the cloud web app is up, but its contents sit
    behind an auth wall — and the OIDC wiring to the central IdP is probed
    honestly (warn, not fail, when the subset doesn't register the client)."""
    try:
        r = session.get(cloud_base + "/", timeout=T)
    except requests.RequestException:
        result.skip("opencloud not running")
        return
    if r.status_code != 200 or not re.search(r"opencloud|owncloud", r.text, re.IGNORECASE):
        result.fail(f"opencloud web UI broken: HTTP {r.status_code}")
        return
    result.ok("opencloud web UI loads")

    # files must not be world-readable: unauthenticated WebDAV is denied
    try:
        dav = session.get(cloud_base + "/remote.php/dav/", timeout=T)
        (result.ok if dav.status_code in (401, 403) else result.fail)(
            "WebDAV auth wall holds (401/403)" if dav.status_code in (401, 403)
            else f"WebDAV answers {dav.status_code} without credentials!"
        )
    except requests.RequestException as e:
        result.fail(f"WebDAV probe failed: {e.__class__.__name__}")

    # OIDC wiring: the IdP must know the cloud's client, otherwise login is
    # a dead end (UI loads, auth fails). Diagnostic warn — the minimal demo
    # subset may legitimately ship without the client registration.
    try:
        disc = session.get(idp_base + "/.well-known/openid-configuration",
                           timeout=T).json()
        az = session.get(disc["authorization_endpoint"], params={
            "client_id": client_id, "response_type": "code",
            "scope": "openid", "nonce": "e2e-wiring-probe",
            "redirect_uri": f"{cloud_base}/oidc-callback.html",
        }, allow_redirects=False, timeout=T)
        if az.status_code in REDIRECTS:
            result.ok("opencloud OIDC client is registered at the IdP")
        elif "App.NotFound" in az.text or "client" in az.text.lower():
            result.warn("opencloud OIDC client NOT registered in this subset "
                        "— web login would fail (register it for full demo)")
        else:
            result.warn(f"opencloud OIDC probe: HTTP {az.status_code} {az.text[:80]}")
    except (requests.RequestException, ValueError) as e:
        result.warn(f"opencloud OIDC probe failed: {e.__class__.__name__}")


def section_sogo_sso(result, session, webmail_base, idp_base, client_id=None):
    """Groupware journey: the webmail SSO contract (Epic C3). SOGo must
    delegate authentication to the IdP: an unauthenticated /SOGo/ REDIRECTS
    to the authorize endpoint (carrying the configured client_id) — a local
    login form is a failure, not a warning. The login page's asset contract
    lives in tests/05-e2e/webmail.py (which walks the whole flow)."""
    # The experimental sogo6 webmail stack (SOGo6-UI/server) answers its own
    # health contract and does not serve /SOGo/ — the SOGo5 probe below would
    # misfire on it. Classify it explicitly instead of failing.
    try:
        h = session.get(webmail_base + "/api/user/v1/health", timeout=T)
        # sogo6 health shape: {status: ok|degraded, version, uptime_seconds,
        # dependencies{database,ldap}} — version 6.x is the giveaway. A
        # degraded stack (no LDAP user source yet) answers 503, so the shape
        # is matched regardless of the status code.
        hj = h.json()
        if str(hj.get("version", "")).startswith("6.") and "dependencies" in hj:
            result.skip(
                f"sogo6 webmail stack detected (health={hj.get('status')}) — "
                "SOGo5 SSO probe not applicable (sogo6 login enablement: "
                "LDAP user source pending)"
            )
            return
    except (requests.RequestException, ValueError):
        pass  # not sogo6 — fall through to the SOGo5 probe

    for path in ("/sogo/", "/SOGo/", "/"):
        try:
            r = session.get(webmail_base + path, allow_redirects=False, timeout=T)
        except requests.RequestException:
            result.skip("sogo not running")
            return
        if r.status_code == 404:
            continue  # wrong path — try root
        loc = r.headers.get("Location", "")
        if r.status_code in REDIRECTS and "/oauth" in loc and "client_id=" in loc:
            az = parse_qs(urlparse(loc).query)
            if client_id and az.get("client_id", [""])[0] != client_id:
                result.fail(
                    f"sogo SSO redirect targets client "
                    f"{az.get('client_id', ['?'])[0]} but .env configures "
                    f"{client_id} — SOGo and the registered OIDC app drifted apart"
                )
            else:
                result.ok("sogo SSO redirect targets the IdP's authorize endpoint")
            return
        if r.status_code in REDIRECTS and loc.startswith(idp_base):
            result.fail(
                f"sogo SSO redirect lands on {loc[:60]} — not the authorize "
                "endpoint (no client_id): SOGo must start the OIDC dance"
            )
            return
        if r.status_code == 200:
            result.fail(
                "sogo reachable but serves a local login — the webmail SSO "
                "(Epic C3) requires SOGo to delegate authentication to the IdP"
            )
            return
        result.fail(f"sogo probe: HTTP {r.status_code} {loc[:60]}")
        return
    result.skip("sogo not running")


def _purge_user(session, idp_base: str, pat: str, uname: str) -> None:
    """Delete any leftover identity with this username (idempotent journeys)."""
    H = {"Authorization": f"Bearer {pat}", "Content-Type": "application/json"}
    lst = session.post(idp_base + "/v2/users", headers=H, json={"queries": [
        {"userNameQuery": {"userName": uname, "method": "TEXT_QUERY_METHOD_EQUALS"}}
    ]}, timeout=T).json()
    for stale in (lst.get("result") or []):
        session.delete(idp_base + f"/v2/users/{stale.get('userId')}",
                       headers=H, timeout=T)


def _provision_user(session, idp_base: str, pat: str, uname: str) -> tuple[str, str]:
    """Create an identity WITH its initial password (admin path — the
    separate /password endpoint is self-service and needs verification).
    Returns (userId, password)."""
    pw = "E2e-" + secrets.token_urlsafe(9) + "!7"
    j = session.post(idp_base + "/v2/users/human", headers={
        "Authorization": f"Bearer {pat}", "Content-Type": "application/json"
    }, json={
        "username": uname,
        "profile": {"givenName": "E2", "familyName": "Throwaway"},
        "email": {"email": f"{uname}@e2e.invalid", "isVerified": True},
        "password": {"password": pw, "changeRequired": False},
    }, timeout=T).json()
    return j.get("userId", ""), pw


def section_user_lifecycle(result: Result, session, disc: dict, client_id: str,
                           callback: str, idp_base: str, lc_pat: str,
                           client_uid: str, pat: str):
    """Identity lifecycle: an operator provisions a user via API, that user
    logs in through the full SSO flow, and after deletion the dead identity
    is rejected. Leftovers from crashed runs are purged first."""
    H = {"Authorization": f"Bearer {pat}", "Content-Type": "application/json"}
    uname = "e2e-throwaway"

    # 0) purge leftovers (crashed previous runs) — the journey must be idempotent
    _purge_user(session, idp_base, pat, uname)
    lst = session.post(idp_base + "/v2/users", headers=H, json={"queries": [
        {"userNameQuery": {"userName": uname, "method": "TEXT_QUERY_METHOD_EQUALS"}}
    ]}, timeout=T).json()
    if lst.get("result"):
        result.ok("purged leftover identity from a previous run")

    # 1) provision: create the user WITH their initial password
    uid, pw = _provision_user(session, idp_base, pat, uname)
    if not uid:
        # `j` is local to _provision_user — never reference it here (NameError
        # on the failure path would mask the real diagnosis).
        result.fail("user provisioning failed: POST /v2/users/human returned "
                    "no userId")
        return
    result.ok(f"provisioned identity {uname} ({uid})")

    try:
        # 2) that user logs in through the full authorization-code flow
        authz, _verifier, _state, _nonce = authorize_url(disc, client_id, callback)
        qs, _sess = api_login(session, idp_base, lc_pat, client_uid, authz,
                              uid, pw)
        if qs.get("code"):
            result.ok("freshly provisioned user completes the SSO flow")
        else:
            result.fail("provisioned user login produced no code")

        # 3) deletion → the dead identity must be rejected while the app is
        #    still alive (isolate the user-lifecycle assertion)
        r = session.delete(idp_base + f"/v2/users/{uid}", headers=H, timeout=T)
        if r.status_code >= 300:
            result.fail(f"user deletion failed: HTTP {r.status_code}")
            return
        result.ok("deleted identity")
        try:
            api_login(session, idp_base, lc_pat, client_uid, authz, uid, pw)
            result.fail("deleted identity was still able to log in")
        except E2EError:
            result.ok("deleted identity is rejected by the IdP")
    finally:
        session.delete(idp_base + f"/v2/users/{uid}", headers=H, timeout=T)


def section_session_isolation(result: Result, session, disc: dict, client_id: str,
                              callback: str, idp_base: str, lc_pat: str,
                              client_uid: str, pat: str):
    """Multi-tenant identity: two coworkers log in, sessions are distinct,
    and logging out one does NOT end the other's session."""
    ua, ub = "e2e-cowork-a", "e2e-cowork-b"
    for u in (ua, ub):
        _purge_user(session, idp_base, pat, u)
    try:
        uid_a, pw_a = _provision_user(session, idp_base, pat, ua)
        uid_b, pw_b = _provision_user(session, idp_base, pat, ub)
        if not uid_a or not uid_b:
            result.fail("session isolation: provisioning failed")
            return

        authz_a, _, _, _ = authorize_url(disc, client_id, callback)
        _, sess_a = api_login(session, idp_base, lc_pat, client_uid, authz_a, uid_a, pw_a)
        authz_b, _, _, _ = authorize_url(disc, client_id, callback)
        _, sess_b = api_login(session, idp_base, lc_pat, client_uid, authz_b, uid_b, pw_b)
        if sess_a["id"] == sess_b["id"]:
            result.fail("two identities share ONE session — isolation broken")
            return
        result.ok("two identities hold distinct IdP sessions")

        # cowork A logs out — cowork B must keep working
        if not terminate(session, idp_base, lc_pat, client_uid,
                         sess_a["id"], sess_a["token"]):
            result.fail("session isolation: logout of cowork A rejected")
            return
        authz_a2, _, _, _ = authorize_url(disc, client_id, callback)
        h = lc_headers(lc_pat, client_uid)
        r = session.get(authz_a2, headers=h, allow_redirects=False, timeout=T)
        m = re.search(r"authRequest=([A-Za-z0-9_:-]+)", r.headers.get("Location", ""))
        if m:
            try:
                finalize(session, idp_base, lc_pat, client_uid, m.group(1),
                         sess_a["id"], sess_a["token"])
                result.fail("cowork A's session survived logout")
            except E2EError:
                result.ok("cowork A's logout sticks")

        try:
            authz_b2, _, _, _ = authorize_url(disc, client_id, callback)
            r = session.get(authz_b2, headers=lc_headers(lc_pat, client_uid),
                            allow_redirects=False, timeout=T)
            m = re.search(r"authRequest=([A-Za-z0-9_:-]+)", r.headers.get("Location", ""))
            if not m:
                result.fail("session isolation: could not open a fresh auth request for B")
                return
            qs_b = finalize(session, idp_base, lc_pat, client_uid,
                            m.group(1), sess_b["id"], sess_b["token"])
            if qs_b.get("code"):
                result.ok("cowork B unaffected by A's logout (session still finalizes)")
            else:
                result.fail("cowork B finalize produced no code")
        except E2EError as e:
            result.fail(f"cowork B collateral damage from A's logout: {e}")
    finally:
        for u in (ua, ub):
            _purge_user(session, idp_base, pat, u)


